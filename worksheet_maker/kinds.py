# 예전 저장 파일의 note/game은 계속 읽되 새 만들기에서는 네 가지만 고른다.
ACTIVE_KINDS = ("standard", "inquiry", "test", "drill")


def for_generation(kind: str) -> str:
    return {"note": "standard", "game": "drill"}.get(kind, kind if kind in ACTIVE_KINDS else "standard")

